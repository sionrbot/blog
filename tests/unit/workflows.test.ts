import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import { describe, expect, it } from 'vite-plus/test';
import { BranchName } from 'release-please/build/src/util/branch-name.js';

const workflow = (name: string) =>
  readFileSync(new URL(`../../.github/workflows/${name}.yml`, import.meta.url), 'utf8');
const ci = workflow('ci');
const quality = ci.slice(ci.indexOf('\n  quality:\n'));
const scriptBlock = quality.match(
  /node --input-type=module <<'NODE'\n([\s\S]*?)\n          NODE/,
)?.[1];
if (!scriptBlock) throw new Error('CI quality gate is missing');
const script = scriptBlock;

function qualityGate(release: boolean, results: Record<string, string>) {
  const jobs = Object.fromEntries(
    Object.entries(results).map(([name, result]) => [name, { result }]),
  );
  return () =>
    runInNewContext(script, {
      process: { env: { RELEASE_PR: String(release), RESULTS: JSON.stringify(jobs) } },
    });
}
const successful = {
  build: 'success',
  'build-tests': 'success',
  'site-audit': 'success',
  'release-builds': 'success',
};

describe('CI required quality check', () => {
  it('requires the production bundle for a Release PR, while ordinary PRs deliberately skip it', () => {
    expect(qualityGate(true, successful)).not.toThrow();
    const ordinary = { ...successful, 'release-builds': 'skipped' };
    expect(qualityGate(false, ordinary)).not.toThrow();
    expect(qualityGate(true, ordinary)).toThrow();
    expect(qualityGate(false, successful)).toThrow();
  });

  it.each(Object.keys(successful))('cannot pass a Release PR when %s did not succeed', (name) => {
    for (const result of ['failure', 'cancelled', 'skipped']) {
      expect(qualityGate(true, { ...successful, [name]: result })).toThrow(name);
    }
  });

  it.each(['build', 'build-tests', 'site-audit'])(
    'cannot pass an ordinary PR when %s did not succeed',
    (name) => {
      for (const result of ['failure', 'cancelled', 'skipped']) {
        expect(
          qualityGate(false, { ...successful, 'release-builds': 'skipped', [name]: result }),
        ).toThrow(name);
      }
    },
  );
});

it('keeps full verification on PRs and does not repeat it on main pushes or during deployment', () => {
  for (const name of ['ci', 'e2e']) {
    const triggers = workflow(name).match(/^on:\n([\s\S]*?)\npermissions:/m)?.[1];
    expect(triggers).toBeDefined();
    expect(triggers).toMatch(/^  pull_request:/m);
    expect(triggers).not.toMatch(/^  push:/m);
  }
  for (const name of ['release-please', 'deploy']) {
    expect(workflow(name)).not.toMatch(/\bpnpm (?:run )?(?:build|check|lint|test:)/);
    expect(workflow(name)).not.toContain('cf-wrangler build');
  }
});

it('starts automatic deployment only from a completed artifact-publication output', () => {
  const release = workflow('release-please');
  const deploy = release.slice(release.indexOf('\n  deploy:\n'));
  expect(deploy).toContain("needs.release.outputs.release_tag != ''");
  expect(deploy).toContain('needs: release');
  expect(deploy).toContain('uses: ./.github/workflows/deploy.yml');
  expect(deploy).toContain('release_tag: ${{ needs.release.outputs.release_tag }}');
});

it('recognizes the component Release PR branch generated by the configured single-package strategy', () => {
  const config = JSON.parse(
    readFileSync(new URL('../../release-please-config.json', import.meta.url), 'utf8'),
  );
  const branch = BranchName.ofComponentTargetBranch(
    config.packages['.']['package-name'],
    'main',
  ).toString();
  for (const name of ['ci', 'e2e']) expect(workflow(name)).toContain(`head.ref == '${branch}'`);
  for (const name of ['release-evidence', 'release-artifacts']) {
    const source = readFileSync(new URL(`../../scripts/${name}.ts`, import.meta.url), 'utf8');
    expect(source).toContain(`pr.head.ref !== '${branch}'`);
  }
});
